import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

// Supply an output path to publish this artifact or copy it to a frontend checkout.
const source = new URL("../src/types/studyApi.ts", import.meta.url);
const output = process.argv[2]
  ? resolve(process.argv[2])
  : fileURLToPath(new URL("../artifacts/study-api.d.ts", import.meta.url));

const content = await readFile(source, "utf8");
if (/^\s*import\s/m.test(content))
  throw new Error(
    "API contracts must be self-contained; remove implementation imports before exporting.",
  );

await mkdir(dirname(output), { recursive: true });

await writeFile(
  output,
  "// Generated by the backend export:contracts command. Do not edit manually.\n" +
    content,
);
console.log(`Exported API contracts to ${output}`);
